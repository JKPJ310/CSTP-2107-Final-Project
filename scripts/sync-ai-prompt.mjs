// Copies the AI's instructions into the edge functions' shared folder (used by ai-chat and
// ai-memory), so src/ai/instructions.md and src/lib/safety.js stay the only places to edit them.
// Run with: npm run ai:sync
import { readFileSync, writeFileSync } from 'node:fs'
import { CRISIS_PHRASES } from '../src/lib/safety.js'

const source = 'src/ai/instructions.md';
const target = 'supabase/functions/_shared/generated.ts';
const markdown = readFileSync(source, 'utf8');

const fail = (problem) => {
    console.error(`ai:sync stopped: ${problem} in ${source}`);
    process.exit(1);
}

// Text of "## <number>. ..." up to the next "## " heading
const section = (number) => {
    const found = markdown.split(/^## /m).find((part) => part.startsWith(`${number}. `));
    if (!found) fail(`section ${number} is missing`);
    return found.slice(found.indexOf('\n') + 1).trim();
}

const version = markdown.match(/^Version:\s*(\S+)/m)?.[1] ?? fail('the "Version:" line is missing');
const systemPrompt = section(1);
const memoryRules = section(3);
const notePrompt = section(4);
const crisisReply = section(2).match(/```\n([\s\S]*?)\n```/)?.[1].trim() ?? fail('the fixed crisis reply block in section 2 is missing');

writeFileSync(target, `// Generated by \`npm run ai:sync\` from ${source} and src/lib/safety.js. Don't edit by hand.

export const PROMPT_VERSION = ${JSON.stringify(version)};

export const SYSTEM_PROMPT = ${JSON.stringify(systemPrompt)};

export const MEMORY_RULES = ${JSON.stringify(memoryRules)};

export const NOTE_PROMPT = ${JSON.stringify(notePrompt)};

export const CRISIS_REPLY = ${JSON.stringify(crisisReply)};

export const CRISIS_PHRASES: string[] = ${JSON.stringify(CRISIS_PHRASES)};
`);

console.log(`ai:sync wrote ${target} (instructions version ${version}, ${systemPrompt.length} characters of system prompt)`);
